import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const read=p=>readFile(new URL('../'+p,import.meta.url),'utf8');
test('Top Companions preserves Explore controls and uses a daily real-data leaderboard',async()=>{
 const html=await read('companions.html'),page=await read('top-companions.html'),css=await read('top-companions.css'),js=await read('js/top-companions-page.js');
 assert.match(html,/class="top-companions-link" href="top-companions.html"/);
 for(const id of ['state','district','city','category','mode','gender-filter','sort','saved-only','results','retry','status'])assert.match(html,new RegExp('id="'+id+'"'));
 assert.match(page,/name="robots" content="noindex,follow"/);
 assert.match(page,/Back to Explore/);
 for(const label of ['Most Active','Most Booked','Top Rated'])assert.ok(page.includes(label));
 assert.doesNotMatch(page,/tc-intro|tc-updated|Top 20 Companions|Find company for your favourite activities|midnight IST/);
 assert.doesNotMatch(js,/tc-updated|updated\.textContent/);
 assert.ok(page.indexOf('class="tc-tabs"')<page.indexOf('id="tc-list"'));
 assert.match(page,/<div class="tc-tabs" role="group" aria-label="Ranking categories">/);
 assert.doesNotMatch(page,/<nav class="tc-tabs"/);
 assert.match(css,/\.tc-tabs\{position:static;inset:auto;box-sizing:border-box;width:100%;display:grid/);
 assert.match(js,/rpc\('top_companions_rankings'/);
 assert.match(js,/slice\(0,20\)/);
 assert.match(js,/browse_public_companions_v3/);
 assert.match(js,/p_public_ids:rows\.map\(row=>row\.public_id\)/);
 assert.match(js,/genderLabel\(row\.public_gender\)/);
 assert.match(js,/value==='male'\?'Male':value==='female'\?'Female':value==='other'\?'Other':''/);
 assert.match(js,/if\(gender\)identity\.append/);
 assert.match(css,/\.tc-identity\{display:flex;flex-direction:column/);
 assert.match(js,/createSignedUrl\(row.photo_path,60\)/);
 assert.match(js,/avatarAsset\(row.photo_path\)/);
 assert.doesNotMatch(page,/About rankings|tc-info|tc-opt-out/);
 assert.doesNotMatch(js,/top_companions_preference/);
 const account=await read('account.html'),accountJs=await read('js/account-page.js');
 assert.match(account,/id="tc-opt-out"/);
 assert.match(accountJs,/top_companions_preference/);
 assert.match(accountJs,/void loadRankingPreference\(\)/);
 assert.doesNotMatch(js,/setInterval|sendBookingEmail|api\.resend\.com/);
 for(const n of [1,2,3])assert.match(css,new RegExp('tc-rank-'+n+'\\{[^}]*text-shadow'));
 const sql=await read('supabase/migrations/20261125082518_top_companions_daily_rankings.sql');
 assert.match(sql,/30 18 \* \* \*/);
 assert.match(sql,/limit 20/);
 assert.match(sql,/s\.points>100/);
 assert.match(sql,/enable row level security/);
});