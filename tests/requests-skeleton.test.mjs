import test from 'node:test';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const source=read('js/requests-page.js');
test('hub and category skeletons are initial-only and never show fake counts',()=>{
 const ids=['request-hub-skeleton','request-list-skeleton','request-menu','request-detail','request-view-count','requests','status','empty','request-view-name'];
 const nodes=Object.fromEntries(ids.map(id=>[id,{hidden:false,classList:{toggle(){},remove(){}},setAttribute(k,v){this[k]=v;}}]));
 const ctx=vm.createContext({$:id=>nodes[id],view:null,requestsReady:false,viewNames:{ongoing:'Ongoing'}});
 vm.runInContext(source.slice(source.indexOf('function setRequestLoading('),source.indexOf('function writeRequestHistory(')),ctx);
 vm.runInContext('setRequestLoading(true)',ctx);
 assert.equal(nodes['request-hub-skeleton'].hidden,false);
 assert.equal(nodes['request-menu'].hidden,true);
 ctx.view='ongoing';
 vm.runInContext('setRequestLoading(true)',ctx);
 assert.equal(nodes['request-list-skeleton'].hidden,false);
 assert.equal(nodes['request-view-count'].hidden,true);
 assert.equal(nodes['request-view-name'].textContent,'Ongoing');
 ctx.requestsReady=true;
 vm.runInContext('setRequestLoading(false)',ctx);
 assert.equal(nodes['request-list-skeleton'].hidden,true);
 assert.equal(nodes.requests.hidden,false);
 assert.equal(nodes['request-view-count'].hidden,false);
 vm.runInContext('setRequestLoading(true)',ctx);
 assert.equal(nodes['request-list-skeleton'].hidden,true);
 ctx.requestsReady=false;
 vm.runInContext('finishRequestLoadingError(new Error("Network error"))',ctx);
 assert.equal(nodes['request-detail'].hidden,true);
 assert.equal(nodes.status.textContent,'Network error');
});
test('five static hub skeleton rows preserve the original five interactive categories',()=>{
 const html=read('requests.html'),css=read('requests-compact.css');
 const hub=html.slice(html.indexOf('id="request-hub-skeleton"'),html.indexOf('id="request-menu"'));
 assert.equal((hub.match(/class="request-hub-card request-sk-card"/g)||[]).length,5);
 assert.equal((html.match(/<button type="button" class="request-hub-card" data-view=/g)||[]).length,5);
 assert.doesNotMatch(hub,/data-count-for|data-view=/);
 assert.match(css,/prefers-reduced-motion:reduce[^\n]*request-sk-shape::after/);
});
